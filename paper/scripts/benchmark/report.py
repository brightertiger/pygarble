"""Render results.md from metrics.json and footprint.json."""

import json
from typing import Any, Dict, List, Optional

from .metrics import RESULTS

FAMILIES = (("Methods at their defaults", ("pygarble", "baseline")),)
METRICS = ("A_capture", "B_precision", "B_recall", "B_fpr")


def cell(estimate: Optional[Dict[str, Any]]) -> str:
    if not estimate or estimate["value"] is None:
        return "n/a"
    text = f"{estimate['value']:.3f}"
    if estimate["ci"]:
        low, high = estimate["ci"]
        text += f" [{low:.3f}, {high:.3f}]"
    return text


def table(header: List[str], rows: List[List[str]]) -> List[str]:
    out = ["| " + " | ".join(header) + " |"]
    out.append("|" + "|".join(" --- " for _ in header) + "|")
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out + [""]


def section(methods: Dict[str, Any], families: tuple) -> List[str]:
    chosen = [n for n, m in methods.items() if m["family"] in families]
    return table(
        ["Method", "A capture", "B precision", "B recall", "B FPR"],
        [[n] + [cell(methods[n][k]) for k in METRICS] for n in chosen],
    )


def write_report(metrics: Dict[str, Any]) -> None:
    rows = metrics["rows"]
    lines = [
        "# Benchmark results",
        "",
        "Generated by `run.py` from `predictions/`; do not edit by hand. "
        "Every method is scored at its own default decision. Values are "
        "point estimates with 95 percent bootstrap intervals "
        f"({metrics['resamples']} row resamples). A has {rows['A']} junk "
        f"rows; B has {rows['B']} rows ({rows['B_positive']} random "
        f"strings, {rows['B_negative']} tweets). Precision is n/a when a "
        "method flags nothing.",
        "",
    ]
    for title, families in FAMILIES:
        lines += [f"## {title}", ""] + section(metrics["methods"], families)
    lines += footprint_section()
    (RESULTS / "results.md").write_text("\n".join(lines).rstrip() + "\n")


def footprint_section() -> List[str]:
    path = RESULTS / "footprint.json"
    if not path.exists():
        return []
    rows = json.loads(path.read_text())["methods"]
    return ["## Footprint", ""] + table(
        [
            "Method",
            "ms per 1,000 texts",
            "import s",
            "install MB",
            "offline",
        ],
        [
            [
                n,
                f"{r['ms_per_1000']:.1f}",
                f"{r['import_s']:.3f}",
                f"{r['install_bytes'] / 1e6:.2f}",
                "yes" if r["offline"] else "no",
            ]
            for n, r in rows.items()
        ],
    )


if __name__ == "__main__":
    write_report(json.loads((RESULTS / "metrics.json").read_text()))
