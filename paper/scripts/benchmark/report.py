"""Render results.md from metrics, footprint and calibration results."""

import json
from typing import Any, Dict, List, Optional

from .metrics import POINTS, RESULTS

FAMILIES = (
    ("Profiles and baselines", ("profile", "baseline")),
    ("Voting modes on the english profile", ("voting",)),
    ("Appendix: single strategies", ("strategy",)),
)
POINT_TITLES = {
    "native": "native decision",
    "fpr1": "cut at 1 percent FPR on B dev tweets",
    "fpr0.1": "cut at 0.1 percent FPR on B dev tweets",
}


def cell(estimate: Optional[Dict[str, Any]]) -> str:
    if not estimate or estimate["value"] is None:
        return "n/a"
    text = f"{estimate['value']:.3f}"
    if estimate["ci"]:
        low, high = estimate["ci"]
        text += f" [{low:.3f}, {high:.3f}]"
    return text


def table(header: List[str], rows: List[List[str]]) -> List[str]:
    out = ["| " + " | ".join(header) + " |"]
    out.append("|" + "|".join(" --- " for _ in header) + "|")
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out + [""]


METRICS = ("A_capture", "B_precision", "B_recall", "B_fpr")
NO_CUT = "no cut reaches target"


def row(name: str, point: Dict[str, Any], extra: List[str]) -> List[str]:
    out = [name]
    if extra:
        out += [f"{point['cut']:.6g}", f"{point['dev_fpr']:.4f}"]
        if not point["reachable"]:
            return out + [NO_CUT] + ["n/a"] * (len(METRICS) - 1)
    return out + [cell(point[k]) for k in METRICS]


def section(methods: Dict[str, Any], families: tuple) -> List[str]:
    chosen = [n for n, m in methods.items() if m["family"] in families]
    lines = ["AUROC on B test:", ""]
    lines += table(
        ["Method", "AUROC"],
        [[n, cell(methods[n]["auroc"])] for n in chosen],
    )
    for point in POINTS:
        lines += [f"At the {POINT_TITLES[point]}:", ""]
        extra = [] if point == "native" else ["cut", "dev FPR"]
        lines += table(
            ["Method"]
            + extra
            + ["A capture", "B precision", "B recall", "B FPR"],
            [row(n, methods[n]["points"][point], extra) for n in chosen],
        )
    return lines


def write_report(metrics: Dict[str, Any]) -> None:
    gate = dict(metrics["checkpoint"])
    saved = RESULTS / "checkpoint.json"
    if saved.exists():
        gate["override"] = json.loads(saved.read_text()).get("override")
    lines = [
        "# Benchmark results",
        "",
        "Generated by `run.py` from `predictions/`; do not edit by hand. "
        "Values are point estimates with 95 percent bootstrap intervals "
        f"({metrics['resamples']} row resamples). A has "
        f"{metrics['rows']['A']} junk rows; B test has "
        f"{metrics['rows']['B_test']} rows.",
        "",
        f"Checkpoint: {gate['method']} capture on A at {gate['point']} is "
        f"{gate['A_capture']:.3f} (floor {gate['floor']}); "
        f"{'passed' if gate['passed'] else 'failed'}."
        + (f" Continued: {gate['override']}" if gate.get("override") else ""),
        "",
    ]
    for title, families in FAMILIES:
        lines += [f"## {title}", ""] + section(metrics["methods"], families)
    lines += footprint_section() + calibration_section()
    (RESULTS / "results.md").write_text("\n".join(lines).rstrip() + "\n")


def footprint_section() -> List[str]:
    path = RESULTS / "footprint.json"
    if not path.exists():
        return []
    rows = json.loads(path.read_text())["methods"]
    return ["## Footprint", ""] + table(
        [
            "Method",
            "ms per 1,000 texts",
            "import s",
            "install MB",
            "offline",
        ],
        [
            [
                n,
                f"{r['ms_per_1000']:.1f}",
                f"{r['import_s']:.3f}",
                f"{r['install_bytes'] / 1e6:.2f}",
                "yes" if r["offline"] else "no",
            ]
            for n, r in rows.items()
        ],
    )


def calibration_section() -> List[str]:
    path = RESULTS / "calibration.json"
    if not path.exists():
        return []
    rows = json.loads(path.read_text())["profiles"]
    return ["## Calibration at target FPR 0.01", ""] + table(
        [
            "Profile",
            "threshold",
            "dev FPR",
            "B test FPR",
            "B test recall",
            "A capture",
        ],
        [
            [
                n,
                f"{r['threshold']:.6g}",
                f"{r['dev_fpr']:.4f}",
                cell(r["B_test_fpr"]),
                cell(r["B_test_recall"]),
                cell(r["A_capture"]),
            ]
            for n, r in rows.items()
        ],
    )


if __name__ == "__main__":
    write_report(json.loads((RESULTS / "metrics.json").read_text()))
